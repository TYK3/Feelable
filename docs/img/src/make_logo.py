"""Generate the Feelable logo SVGs (mark + outlined wordmark).

The wordmark is Inter Display ExtraBold (SIL OFL) converted to paths, so the
SVG looks identical everywhere without loading a font.

usage: python docs/img/src/make_logo.py   (from the repo root)
writes: web/public/{favicon,logo,logo-wordmark}.svg and docs/img/src/wordmark-path.json
"""
import json
import pathlib

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[3]
FONT = "/usr/share/fonts/opentype/inter/InterDisplay-ExtraBold.otf"

INK = "#17171C"
BANANA = "#FFD23F"
CREAM = "#FFFBF0"

# The mark: an "F" whose stem is a column of raised braille dots and whose two
# arms are hand-drawn strokes, sketch + touch in one shape. 64x64 grid.
MARK_BODY = (
    f'<rect x="2" y="2" width="60" height="60" rx="15" fill="{BANANA}"/>'
    f'<path d="M19 18C27 14.5 38 20 49 15.5" fill="none" stroke="{INK}" stroke-width="7.5" stroke-linecap="round"/>'
    f'<path d="M29 35.5C34 33.5 38.5 36.5 44 34" fill="none" stroke="{INK}" stroke-width="7" stroke-linecap="round"/>'
    f'<circle cx="19.5" cy="29" r="5" fill="{INK}"/>'
    f'<circle cx="19.5" cy="40" r="5" fill="{INK}"/>'
    f'<circle cx="19.5" cy="51" r="5" fill="{INK}"/>'
)


def text_path(text: str, size: float, tracking_em: float = -0.02, kern: dict | None = None):
    """Return (svg path d, width, cap height) for `text` at font size `size`, baseline at y=0."""
    font = TTFont(FONT)
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    s = size / upm
    kern = kern or {}
    x = 0.0
    parts = []
    for i, ch in enumerate(text):
        name = cmap[ord(ch)]
        pen = SVGPathPen(gs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        # flip y (font units are y-up)
        gs[name].draw(TransformPen(pen, (s, 0, 0, -s, x, 0)))
        parts.append(pen.getCommands())
        x += gs[name].width * s + tracking_em * size
        if i + 1 < len(text):
            x += kern.get(ch + text[i + 1], 0) * size
    x -= tracking_em * size
    cap = font["OS/2"].sCapHeight * s
    return " ".join(parts), x, cap


def main() -> None:
    pub = ROOT / "web" / "public"
    pub.mkdir(parents=True, exist_ok=True)

    mark = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">{MARK_BODY}</svg>\n'
    (pub / "favicon.svg").write_text(mark)
    (pub / "logo.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="512" height="512">'
        f"<title>Feelable</title>{MARK_BODY}</svg>\n"
    )

    # Wordmark: mark (64 high) + text whose cap height ~ 0.5 of the mark.
    size = 44
    d, w, cap = text_path("Feelable", size, tracking_em=-0.025)
    gap = 16
    baseline = 32 + cap / 2
    total_w = 64 + gap + w
    wm = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w:.1f} 64" width="{total_w * 2:.0f}" height="128">'
        "<title>Feelable</title>"
        f"<style>.wm{{fill:{INK}}}@media (prefers-color-scheme:dark){{.wm{{fill:{CREAM}}}}}</style>"
        f"{MARK_BODY}"
        f'<path class="wm" transform="translate({64 + gap} {baseline:.2f})" d="{d}"/>'
        "</svg>\n"
    )
    (pub / "logo-wordmark.svg").write_text(wm)

    # Path data for the React component (unit: font size 44, baseline 0).
    (ROOT / "docs" / "img" / "src" / "wordmark-path.json").write_text(
        json.dumps({"d": d, "width": round(w, 2), "cap": round(cap, 2), "size": size, "gap": gap})
    )
    write_component(d, total_w, gap, baseline)
    print(f"wordmark width {w:.1f}, cap {cap:.1f}")


def write_component(d: str, total_w: float, gap: int, baseline: float) -> None:
    tsx = f'''// Feelable logo. OWNER: Brand. Generated by docs/img/src/make_logo.py (edit there, re-run).
// The mark: an "F" whose stem is a column of raised braille dots and whose arms are
// hand-drawn strokes. Sketch + touch in one shape. Pure inline SVG, no fetches.
// The wordmark uses currentColor, so it follows the surrounding text colour
// (ink on cream, cream on dark). The yellow tile reads on both.

const WORDMARK_D =
  "{d}";

export function Logo({{
  size = 32,
  withWordmark = false,
  className,
}}: {{
  size?: number;
  withWordmark?: boolean;
  className?: string;
}}) {{
  const vbW = withWordmark ? {total_w:.1f} : 64;
  return (
    <svg
      className={{className}}
      width={{(size * vbW) / 64}}
      height={{size}}
      viewBox={{`0 0 ${{vbW}} 64`}}
      role="img"
      aria-label="Feelable"
      focusable="false"
    >
      <rect x="2" y="2" width="60" height="60" rx="15" fill="{BANANA}" />
      <path d="M19 18C27 14.5 38 20 49 15.5" fill="none" stroke="{INK}" strokeWidth="7.5" strokeLinecap="round" />
      <path d="M29 35.5C34 33.5 38.5 36.5 44 34" fill="none" stroke="{INK}" strokeWidth="7" strokeLinecap="round" />
      <circle cx="19.5" cy="29" r="5" fill="{INK}" />
      <circle cx="19.5" cy="40" r="5" fill="{INK}" />
      <circle cx="19.5" cy="51" r="5" fill="{INK}" />
      {{withWordmark && <path transform="translate({64 + gap} {baseline:.2f})" d={{WORDMARK_D}} fill="currentColor" />}}
    </svg>
  );
}}

export default Logo;
'''
    (ROOT / "web" / "src" / "components" / "Logo.tsx").write_text(tsx)


if __name__ == "__main__":
    main()
